"use strict";

/**
 * Flags a single source file growing past a comfortable size.
 *
 * A large file is not wrong by itself, but it is a reliable proxy for a
 * module that has stopped having one job — this rule exists to make that
 * moment visible instead of silent. It only ever asks: a line count is a
 * heuristic, never grounds for a denial.
 */

const path = require("path");
const { ask, pass } = require("../lib/decision");
const { globToRegex } = require("../lib/project-resolver");

/** Tool names this rule inspects, shared with every other file-content rule. */
const FILE_TOOLS = /^(Write|Edit|MultiEdit|NotebookEdit|apply_patch|write_file)$/;

/** Extensions never worth counting: data, docs and generated snapshots. */
const SKIP_EXTENSIONS = new Set([".json", ".md", ".snap", ".lock"]);

/** Exact lock-file names whose extension alone would not mark them. */
const LOCK_FILE_NAMES = new Set(["pnpm-lock.yaml", "npm-shrinkwrap.json"]);

/** A path segment that marks output nobody hand-edits. */
const GENERATED_PATH_SEGMENT = /(^|\/)(dist|build|bin|obj|generated|\.generated)(\/|$)/i;

/** A file-name suffix used for machine-written source. */
const GENERATED_NAME_SUFFIX = /\.(g|generated|designer|min)\.[a-z0-9]+$/i;

/** A header comment tools commonly stamp into what they emit. */
const GENERATED_CONTENT_MARKER = /@generated\b|<auto-generated|auto-?generated by/i;

/**
 * Splits a path into its POSIX-separated relative form, its base name and
 * its lower-cased extension.
 *
 * @param {object} ctx The evaluation context.
 * @returns {{rel: string, base: string, ext: string}} The decomposed path;
 * every field is `""` when `ctx.filePath` is empty.
 */
function splitPath(ctx) {
  const filePath = ctx.filePath || "";
  if (!filePath) return { rel: "", base: "", ext: "" };

  const boundary = (ctx.git && ctx.git.repoRoot) || ctx.cwd || "";
  let rel = filePath;
  if (boundary) {
    try {
      const candidate = path.relative(boundary, filePath);
      if (candidate && !candidate.startsWith("..") && !path.isAbsolute(candidate)) rel = candidate;
    } catch {
      // Fall back to the raw path.
    }
  }
  rel = rel.replace(/\\/g, "/");

  const base = rel.split("/").pop() || "";
  const dot = base.lastIndexOf(".");
  const ext = dot > 0 ? base.slice(dot).toLowerCase() : "";
  return { rel, base, ext };
}

/**
 * Checks whether a path falls under any of the project's `notOurs` globs.
 *
 * @param {string} rel The path to test, relative and POSIX-separated.
 * @param {object} project The resolved project configuration.
 * @returns {boolean} `true` when `rel` matches an entry in
 * `project.notOurs`.
 */
function isNotOurs(rel, project) {
  const globs = (project && project.notOurs) || [];
  for (const glob of globs) {
    const re = globToRegex(glob);
    if (re && re.test(rel)) return true;
  }
  return false;
}

/**
 * The file's whole content after this write — the question this rule
 * actually asks ("how many lines is the file"), never only what a decoded
 * `Edit`/`MultiEdit`/`apply_patch` update happens to insert. Falls back to
 * `ctx.content` when reconstruction failed (`resultingContent: null`): a
 * `Write` or a brand-new `apply_patch` add already has `content ===
 * resultingContent` (nothing changes for those), and an unreconstructable
 * update degrades to counting only what it inserts rather than staying
 * silent — the same conservative direction this `ask`-only rule already
 * takes on every other "nothing to measure" case (empty content, no
 * threshold configured).
 *
 * @param {object} ctx The evaluation context.
 * @returns {string} The whole-file content to measure.
 */
function wholeFileContent(ctx) {
  return typeof ctx.resultingContent === "string" ? ctx.resultingContent : ctx.content || "";
}

/**
 * Whether this write leaves the file SHORTER than it already was.
 *
 * An oversized file that predates this threshold is exactly the file the
 * standard wants split, and splitting it means editing it. Firing on that
 * edit punishes the work being asked for: measured on a real session, this
 * rule stopped an agent part-way through lifting a shared helper out of a
 * 1808-line component — a change that would have left the file smaller —
 * and on Codex, where an `ask` is a hard stop, that ended the refactor.
 *
 * Deliberately "shorter", not "under the threshold": a file that big is not
 * fixed in one write, and demanding it clear the limit in a single step is
 * the same wall by another name. Moving in the right direction is enough.
 *
 * @param {object} ctx The evaluation context.
 * @param {number} lines The line count this write would leave behind.
 * @returns {boolean} `true` when the file exists and is losing lines.
 */
function isShrinking(ctx, lines) {
  if (typeof ctx.readFile !== "function" || !ctx.filePath) return false;
  const current = ctx.readFile(ctx.filePath);
  if (typeof current !== "string" || current === "") return false;
  return lines < current.split("\n").length;
}

/**
 * Decides whether a write falls outside this rule's concern entirely.
 *
 * @param {object} ctx The evaluation context.
 * @param {{rel: string, base: string, ext: string}} loc The decomposed path.
 * @returns {boolean} `true` when the file is data, a lock file, generated
 * output, or under a `notOurs` path.
 */
function isExempt(ctx, loc) {
  if (!loc.rel) return true;
  if (SKIP_EXTENSIONS.has(loc.ext)) return true;
  if (LOCK_FILE_NAMES.has(loc.base.toLowerCase())) return true;
  if (GENERATED_PATH_SEGMENT.test(loc.rel) || GENERATED_NAME_SUFFIX.test(loc.base)) return true;
  if (GENERATED_CONTENT_MARKER.test(wholeFileContent(ctx))) return true;
  if (isNotOurs(loc.rel, ctx.project)) return true;
  return false;
}

module.exports = {
  id: "file-size-limit",
  title: "Nudge on a source file growing past a comfortable size",
  events: ["PreToolUse"],
  tools: FILE_TOOLS,
  defaultAction: "ask",

  /** which catalogue group this rule belongs to */
  group: "code",

  /**
   * Frontend-only. The thresholds in `limits.fileLines` are frontend-agreed
   * — no backend threshold exists yet, and the mechanism this rule uses
   * (`requiresConfig`) already keeps a project silent until one is set. This
   * `stacks` field is a second, independent reason for the same silence: even
   * once a backend team agrees a number, it would need to be judged against
   * a genuinely different notion of "one file" (a `.cs` type is not a `.tsx`
   * component), so the threshold itself, not only its value, is treated as
   * frontend-specific rather than stack-agnostic-but-unconfigured.
   */
  stacks: ["frontend"],

  /** an existing oversized file predates this threshold; splitting it is a refactor suggestion, not a requirement for touching it */
  newCodeOnly: true,

  /**
   * A size nudge, never a request for the developer's decision — the title
   * of this rule says as much. On a host with no interactive ask it is
   * surfaced rather than blocking; see `core/engine.js`'s step 10.
   */
  advisoryAsk: true,

  /**
   * No invented default: a project that has not agreed a threshold gets no
   * size check at all, rather than inheriting a number nobody chose for it.
   */
  requiresConfig: ["limits.fileLines"],

  /**
   * @param {object} ctx The evaluation context.
   * @returns {null | {action: "ask", reason: string, fix?: string}} `ask`
   * when the file's line count clears the project's threshold, `null`
   * otherwise — including when the threshold itself is not a number, which
   * `requiresConfig` alone cannot guarantee since `limits.fileLines` may be
   * present without an `ask` field.
   */
  evaluate(ctx) {
    const loc = splitPath(ctx);
    if (isExempt(ctx, loc)) return pass();

    // R3: "how many lines is the resulting file" — the whole-file question,
    // not "how many lines did this write insert". See wholeFileContent's own
    // doc comment.
    const content = wholeFileContent(ctx);
    if (!content) return pass();

    const lines = content.split("\n").length;
    const limits = (ctx.project && ctx.project.limits && ctx.project.limits.fileLines) || {};
    if (typeof limits.ask !== "number") return pass();
    const askAt = limits.ask;

    if (lines <= askAt) return pass();
    if (isShrinking(ctx, lines)) return pass();

    return ask(
      `"${loc.base}" is ${lines} lines, past the ${askAt}-line threshold for a single file.`,
      "Split the file along its responsibilities before it grows further.",
    );
  },
};
